import pandas as pd
import numpy as np
import xgboost as xgb
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score

# 1. Load Data
names = ['age','sex','cp','trestbps','chol','fbs','restecg','thalach','exang','oldpeak','slope','ca','thal','num']
df = pd.read_csv("data/processed.cleveland.data", names=names)

# 2. Process Target and Missing Values
df['target'] = (df['num'] > 0).astype(int)
df = df.replace('?', np.nan)
df['ca'] = pd.to_numeric(df['ca'])
df['thal'] = pd.to_numeric(df['thal'])

# Fill missing values with median so XGBoost doesn't stumble on NaNs
df['ca'] = df['ca'].fillna(df['ca'].median())
df['thal'] = df['thal'].fillna(df['thal'].median())

X = df.drop(['target','num'], axis=1)
y = df['target']

# 3. Fixed Hyperparameters
params = {
    'objective': 'binary:logistic',
    'eval_metric': 'auc',
    'max_depth': 4,                  # Set to a stable 4
    'eta': 0.03,                     # Slower learning rate to prevent overfitting
    'subsample': 0.8,                # FIX: Train on 80% of rows (not 3%!)
    'colsample_bytree': 0.8          # Train on 80% of columns
}

# 4. Train/Test Split
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, stratify=y, random_state=42)
y_train_clean = y_train.astype(int)


model = xgb.XGBClassifier(**params)
model.fit(X_train, y_train_clean)
disease_row = pd.DataFrame([{ #Dieased  person
    'age': 64, 'sex': 1, 'cp': 4, 'trestbps': 141, 'chol': 302,
    'fbs': 1, 'restecg': 1, 'thalach': 98, 'exang': 1,
    'oldpeak': 5.2, 'slope': 3, 'ca': 1, 'thal': 6
}])

healthy_row = pd.DataFrame([{  #Healthy person
    'age': 46, 'sex': 1, 'cp': 3, 'trestbps': 101, 'chol': 211,
    'fbs': 0, 'restecg': 0, 'thalach': 193, 'exang': 0,
    'oldpeak': 0.1, 'slope': 1, 'ca': 0, 'thal': 3
}])

new_patient = pd.DataFrame([{ #New patient
    'age': 50, 'sex': 1, 'cp': 2, 'trestbps': 120, 'chol': 250,
    'fbs': 0, 'restecg': 0, 'thalach': 180, 'exang': 0,
    'oldpeak': 0.0, 'slope': 1, 'ca': 0, 'thal': 2
}])

print("Disease-leaning prediction:", model.predict(disease_row))
print("Healthy-leaning prediction:", model.predict(healthy_row))
print("New patient prediction (Generated by tab):", model.predict(new_patient))




